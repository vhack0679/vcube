use vcube2;
SELECT * FROM employee;
WITH TEMP AS(SELECT *  , DENSE_RANK() OVER(ORDER BY SALARY DESC) AS "SAL_RANK" FROM EMPLOYEE)
SELECT * FROM TEMP WHERE SAL_RANK IN(1,2,3);
SELECT *,ROW_NUMBER() OVER (ORDER BY SALARY DESC) AS "ROW_NUM" FROM employee;
WITH TEMP AS(SELECT *  , DENSE_RANK() OVER(ORDER BY SALARY DESC) AS "SAL_RANK" FROM EMPLOYEE)
SELECT *, MAX(SALARY) OVER()- SALARY AS DIFF_SAL FROM employee;
WITH TEMP AS(SELECT*,DENSE_RANK() OVER (ORDER BY SALARY DESC) AS" SAL_RANK" FROM employee)
SELECT * FROM TEMP WHERE SAL_RANK=2;
SELECT *,AVG(SALARY) OVER(PARTITION BY DEPT_ID) AS AVG FROM employee;
SELECT * , LAG(SALARY) OVER() AS "PREV" FROM employee;